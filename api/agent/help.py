def get_help(topic: str | None = None) -> dict:
    """ヘルプ情報を返す。

    トピックの解決順序:
    1. 完全一致（_HELP_CONTENTS のキー）
    2. エイリアス一致（_TOPIC_ALIASES）
    3. 部分一致（キーまたはエイリアスに topic が含まれる）
    4. フォールバック（overview）

    Args:
        topic: 知りたい機能のトピック。None で全体概要。

    Returns:
        {"help": "ヘルプテキスト"} 形式の辞書。
    """
    if not topic:
        return {"help": _HELP_CONTENTS["overview"]}

    # 1. 完全一致
    if topic in _HELP_CONTENTS:
        return {"help": _HELP_CONTENTS[topic]}

    # 2. エイリアス一致
    resolved = _TOPIC_ALIASES.get(topic)
    if resolved and resolved in _HELP_CONTENTS:
        return {"help": _HELP_CONTENTS[resolved]}

    # 3. 部分一致（トピックキー内に topic が含まれるか）
    for key in _HELP_CONTENTS:
        if topic in key:
            return {"help": _HELP_CONTENTS[key]}

    # 3b. 部分一致（エイリアスキー内に topic が含まれるか）
    for alias, resolved_key in _TOPIC_ALIASES.items():
        if topic in alias and resolved_key in _HELP_CONTENTS:
            return {"help": _HELP_CONTENTS[resolved_key]}

    # 4. フォールバック
    return {"help": _HELP_CONTENTS["overview"]}
